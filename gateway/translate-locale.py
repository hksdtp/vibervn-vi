#!/usr/bin/env python3
"""bundled locales/en.yaml -> locales-vi.yaml (user-overlay catalog, installed to ~/.vibervnbot/locales/vi.yaml).
Resumable via locale-cache.json. Run with the payload venv python (needs PyYAML).
Env: SUB2API_KEY (else read from /Users/nihdev/spec-ade-native/.env.local), SUB2API_BASE, SUB2API_MODEL."""
import json, os, re, sys, time, concurrent.futures as cf, urllib.request
import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
PAYLOAD = os.environ.get("GATEWAY_PAYLOAD", "/Applications/ViberVN Bot.app/Contents/Resources/agent-payload/vibervnbot-agent")
BASE = os.environ.get("SUB2API_BASE", "http://100.115.227.21:8090/v1")
MODEL = os.environ.get("SUB2API_MODEL", "gpt-6-sol")
KEY = os.environ.get("SUB2API_KEY") or re.search(r"^SUB2API_KEY=(.*)$", open("/Users/nihdev/spec-ade-native/.env.local").read(), re.M).group(1).strip("\"'")
CACHE = os.path.join(HERE, "locale-cache.json")
cache = json.load(open(CACHE)) if os.path.exists(CACHE) else {}

en = yaml.safe_load(open(f"{PAYLOAD}/locales/en.yaml", encoding="utf-8"))

def leaves(node, path=()):
    for k, v in node.items():
        if isinstance(v, dict): yield from leaves(v, path + (str(k),))
        else: yield path + (str(k),), v

# Keys whose literal text is matched or typed by users/code stay English: hotkey prompts like "[o]nce" and *_inputs word lists.
def keep(path, v):
    return (not isinstance(v, str) or not re.search(r"[^\W\d_]", v) or re.search(r"\[\w\]", v)
            or any(p == "inputs" or p.endswith("_inputs") for p in path))

SYSTEM = """You localize ViberVN Bot (a desktop AI agent; this is its gateway/CLI/chat text) from English to Vietnamese.
Tone: casual, direct, friendly; address the user as "bạn". Natural Vietnamese software wording, keep short strings short.
Keep unchanged: product/brand names (ViberVN Bot, Claude, OpenAI, Telegram...), technical terms (API, token, model, plugin, skill, prompt, MCP, CLI, gateway, cron, webhook), slash commands (/new), CLI commands and flags (vibervnbot config set ...), config keys, file paths, env vars, emoji, URLs, keyboard keys.
PRESERVE EXACTLY: {name} placeholders, %s/%d, markdown, backticks, newlines, leading/trailing whitespace, escape sequences, bullet/box characters.
Input: JSON {"id": {"key": "<dotted key for context>", "text": "..."}}. Output ONLY JSON {"id": "<vietnamese>"} for every id, no code fences."""

def tokens(s):
    return sorted(re.findall(r"\{[^{}]*\}|%[sd]|`[^`]*`|https?://\S+|(?<![\w/])/[a-z][\w-]*|\n|\\n", s))

def chat(msgs):
    for a in range(6):
        try:
            req = urllib.request.Request(f"{BASE}/chat/completions", json.dumps({"model": MODEL, "messages": msgs}).encode(),
                                         {"content-type": "application/json", "authorization": f"Bearer {KEY}"})
            return json.load(urllib.request.urlopen(req, timeout=300))["choices"][0]["message"]["content"]
        except Exception as e:
            if a == 5: raise
            time.sleep(2 * (a + 1))

def batch(items):
    payload = {str(i): {"key": ".".join(p), "text": v} for i, (p, v) in enumerate(items)}
    try:
        res = json.loads(re.sub(r"^```(?:json)?\s*|\s*```$", "", chat([{"role": "system", "content": SYSTEM}, {"role": "user", "content": json.dumps(payload, ensure_ascii=False)}]).strip()))
    except Exception:
        return 0
    n = 0
    for i, (p, v) in enumerate(items):
        out = res.get(str(i))
        if isinstance(out, str) and out.strip() and tokens(out) == tokens(v):
            cache[v] = out; n += 1
    return n

todo = {}
for p, v in leaves(en):
    if not keep(p, v) and v not in cache: todo.setdefault(v, p)
todo = [(p, v) for v, p in todo.items()]
print(f"todo={len(todo)} cached={len(cache)}", flush=True)
for rnd in range(4):
    if not todo: break
    chunks = [todo[i:i + 25] for i in range(0, len(todo), 25)]
    with cf.ThreadPoolExecutor(6) as ex: list(ex.map(batch, chunks))
    json.dump(cache, open(CACHE, "w"), ensure_ascii=False, indent=1)
    todo = [(p, v) for p, v in todo if v not in cache]
    print(f"round {rnd}: remaining={len(todo)}", flush=True)
if todo: sys.exit(f"{len(todo)} strings failed validation: {[ '.'.join(p) for p, _ in todo[:10]]}")

tree = {}
for p, v in leaves(en):
    if isinstance(v, str) and v in cache:
        d = tree
        for s in p[:-1]: d = d.setdefault(s, {})
        d[p[-1]] = cache[v]
with open(os.path.join(HERE, "locales-vi.yaml"), "w", encoding="utf-8") as f:
    f.write("# Vietnamese overlay for ViberVN Bot gateway (generated by translate-locale.py; partial layer, rest falls back to en)\n")
    yaml.safe_dump(tree, f, allow_unicode=True, width=10**6, sort_keys=False, default_flow_style=False)
print("wrote locales-vi.yaml")
